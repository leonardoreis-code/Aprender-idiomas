// E2E do treinador ao vivo (modo digitado): marcação em tempo real + conserto em degraus.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const URL = process.env.URL ?? 'http://localhost:8787/';
const OUT = process.env.OUT ?? '.';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 420, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && !/fonts|favicon|Failed to load resource/.test(m.text()) && errors.push(m.text()));
await page.goto(URL);
await page.evaluate(() => localStorage.setItem('fluente:v1', JSON.stringify({ onboarded: true, profile: { name: 'Leo', level: 'fala', goals: ['trabalho'], minutes: 25 } })));
await page.goto(URL + '#falar'); await page.reload(); await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/c1-falar.png`, fullPage: true });
await page.getByRole('button', { name: /Treinador ao vivo/ }).first().click();
await page.screenshot({ path: `${OUT}/c2-pick.png`, fullPage: true });
await page.getByRole('button', { name: /Daily standup/ }).click();
await page.getByRole('button', { name: /digitar/ }).click();
const box = page.getByLabel('Sua resposta em inglês');
await box.pressSequentially('Yesterday I go to the office and she work late', { delay: 15 });
await page.screenshot({ path: `${OUT}/c3-live-marks.png` });
const liveMarks = await page.locator('.live-text .live-miss').allTextContents();
