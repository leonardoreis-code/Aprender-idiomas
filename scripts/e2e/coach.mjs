console.log(JSON.stringify({ liveMarks, repairs: st.repairs.map((r) => `${r.rule}@${r.level}`), repN: day.repN, repSelf: day.repSelf, notebook: st.notebook.map((n) => n.en), clean: !!clean, overflow, errors }, null, 1));
await browser.close();
process.exit(errors.length || overflow || st.repairs.length !== 2 ? 1 : 0);
