await page.screenshot({ path: `${OUT}/c6-repair-l4.png` });
await again.fill('she works late'); await page.getByRole('button', { name: 'Enviar' }).click();
await page.waitForTimeout(1900);
await page.screenshot({ path: `${OUT}/c7-after.png` });
await page.getByRole('button', { name: 'Próxima pergunta' }).click();
await page.getByLabel('Sua resposta em inglês').fill('Today I am going to review the pull request');
await page.getByRole('button', { name: 'Enviar' }).click(); await page.waitForTimeout(300);
const clean = await page.getByText('Frase limpa').count();
await page.getByRole('button', { name: 'Próxima pergunta' }).click();
await page.getByRole('button', { name: /Encerrar/ }).click(); await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/c8-summary.png`, fullPage: true });
const st = await page.evaluate(() => JSON.parse(localStorage.getItem('fluente:v1')));
const day = Object.values(st.daily)[0];
for (const h of ['#fluencia', '#reconto', '#eco', '#evolucao', '#inicio']) { await page.goto(URL + h); await page.waitForTimeout(250); }
await page.goto(URL + '#reconto'); await page.waitForTimeout(200); await page.screenshot({ path: `${OUT}/c9-reconto.png`, fullPage: true });
